import random
random.seed(0x4E1D5)   # fixed seed -> reproducible masks
def masks(nbits, width):
    out=[]
    for _ in range(nbits):
        while True:
            m=random.getrandbits(width)
            if bin(m).count('1') >= width//3: break
        out.append(m)
    return out
def func(name, outw, inw, ms):
    terms = ",\n            ".join("^(k & %d'h%x)" % (inw, m) for m in reversed(ms))
    return ("    function [%d:0] %s;\n        input [%d:0] k;\n        begin\n"
            "            %s = {\n            %s};\n        end\n    endfunction\n") % (outw-1, name, inw-1, name, terms)
txt  = "    // H3 universal hash family: each output bit = XOR of a fixed random subset of key bits.\n"
txt += "    // Masks are generated by gen_h3.py (fixed seed). Change the seed to get a different hash set.\n"
txt += func("h3_sk0", 10, 35, masks(10,35))
txt += func("h3_sk1", 10, 35, masks(10,35))
txt += func("h3_bl" , 14, 80, masks(14,80))
open("h3_funcs.txt","w").write(txt)
print(len(txt))
